import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const sections = new Map([
  ["Local Desktop & Small Servers", "local"],
  ["Throughput Servers & Orchestration", "serving"],
  ["General Model Libraries", "library"],
  ["Image, Video & Speech Workflows", "media"],
  ["Browser, Mobile & Edge", "edge"],
]);

const specialRoute = new Map([
  ["llama.cpp", "native-api"], ["Ollama", "native-api"],
  ["LM Studio", "native-api"], ["Radium", "native-api"],
  ["vLLM", "native-api"], ["SGLang", "native-api"],
  ["NVIDIA Triton", "native-api"], ["OpenVINO Model Server", "native-api"],
  ["ComfyUI", "workflow"], ["InvokeAI", "workflow"],
  ["AUTOMATIC1111 WebUI", "workflow"], ["SD WebUI Forge", "workflow"],
  ["SwarmUI", "workflow"], ["NVIDIA Dynamo", "orchestrator"],
  ["Ray Serve LLM", "orchestrator"], ["BentoML", "orchestrator"],
  ["HF Accelerate", "device-layer"],
]);

export function parseCatalog(markdown) {
  let group = null;
  const records = [];
  for (const line of markdown.split(/\r?\n/)) {
    if (line.startsWith("## ")) {
      group = sections.get(line.slice(3).trim()) ?? null;
      continue;
    }
    if (!group || !line.startsWith("| **")) continue;
    const fields = line.split("|").slice(1, -1).map((part) => part.trim());
    if (fields.length !== 6) throw new Error(`Malformed runtime row: ${line}`);
    const [, name, role] = /^\*\*(.+?)\*\* \((.+)\)$/.exec(fields[0]) ?? [];
    const [, docs] = /^\[Docs\]\((https:\/\/[^)]+)\)$/.exec(fields[5]) ?? [];
    if (!name || !role || !docs) throw new Error(`Runtime row missing name, role or source: ${line}`);
    const id = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    const install = name === "llama.cpp" ? "bundled-windows"
      : name === "LM Studio" ? "official-separate-installer"
      : group === "edge" ? "platform-gated"
      : "official-download";
    records.push({ id, name, group, role, formats: fields[1], modelExamples: fields[2],
      purpose: fields[3], requirements: fields[4], documentation: docs,
      route: specialRoute.get(name) ?? (group === "library" || group === "edge" ? "runner" : "compatible-api"),
      install, support: "catalogued" });
  }
  if (records.length !== 63) throw new Error(`Expected 63 catalog entries; found ${records.length}`);
  if (new Set(records.map((item) => item.id)).size !== records.length) {
    throw new Error("Runtime ids must be unique");
  }
  return records;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const records = parseCatalog(readFileSync("docs/reference/runtime-catalog.md", "utf8"));
  mkdirSync("src/lib/runtimes", { recursive: true });
  writeFileSync("src/lib/runtimes/catalog.json", `${JSON.stringify(records, null, 2)}\n`);
  mkdirSync("docs/architecture", { recursive: true });
  const lines = [
    "# Runtime coverage and packaging baseline", "",
    "Generated by `node scripts/generate-runtime-catalog.mjs` from `docs/reference/runtime-catalog.md`.",
    "Catalogued means an integration route and source are recorded; it does not mean installed or verified.",
    "No model weights or third-party app installers are bundled. The Windows installer build includes a pinned verified llama.cpp executable and its CUDA libraries.",
    "That Windows packaging recipe has not been run in this Linux workspace; a live Windows installer build is still required.",
    "LM Studio is a separate installation; OpenAI and Anthropic are built-in hosted provider connectors.",
    "", "| Runtime | Route | Installation | Status | Documentation |", "| --- | --- | --- | --- | --- |",
    ...records.map((r) => `| ${r.name} | ${r.route} | ${r.install} | ${r.support} | [Source](${r.documentation}) |`), "",
  ];
  writeFileSync("docs/architecture/runtime-coverage.md", lines.join("\n"));
  console.log(`Generated ${records.length} catalogued runtime records`);
}
